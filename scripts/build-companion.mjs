import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync, symlinkSync, rmSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";

if (process.platform !== "darwin") throw new Error("Native companion build requires macOS and Xcode Command Line Tools");
const root = fileURLToPath(new URL("../", import.meta.url));
const native = `${root}packages/companions/native`;
const bundle = `${native}/CodexBridge Companions.app`;
mkdirSync(`${root}.local/swift-cache`, { recursive: true });
mkdirSync(`${bundle}/Contents/MacOS`, { recursive: true });
mkdirSync(`${bundle}/Contents/Resources`, { recursive: true });
// LaunchServices gives the app its own privacy identity; keep its artwork inside its signed bundle.
const artwork = ["team-atlas.png", "head-atlas.png", "body-atlas.png", "mixed-head-atlas.png", "mixed-body-atlas.png", "facial-v3.png"];
// This directory is generated by this build; stale full-body clips must not remain installed.
for (const name of readdirSync(`${bundle}/Contents/Resources`)) {
  if (!artwork.includes(name)) rmSync(`${bundle}/Contents/Resources/${name}`, { recursive: true, force: true });
}
for (const name of artwork) {
  const source = `${root}packages/companions/assets/${name}`;
  const target = `${bundle}/Contents/Resources/${name}`;
  if (existsSync(source)) copyFileSync(source, target);
  else rmSync(target, { force: true });
}
// Only authored runtime layers enter the bundle, never ImageGen sources or review previews.
const expansion = `${root}packages/companions/assets/expansion`;
for (const name of ["manifest.json", "poses.json"]) {
  if (!existsSync(`${expansion}/${name}`)) continue;
  const manifest = JSON.parse(readFileSync(`${expansion}/${name}`, "utf8"));
  const images = Object.values(manifest.characters).flatMap(character => [
    ...character.layers.map(layer => layer.file), character.face.file,
  ]);
  for (const file of [name, ...new Set(images)]) {
    if (file.startsWith("/") || file.split("/").includes("..")) throw new Error("Invalid rig asset path");
    const target = join(bundle, "Contents/Resources/expansion", file);
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(join(expansion, file), target);
  }
}
writeFileSync(`${bundle}/Contents/Info.plist`, `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleIdentifier</key><string>dev.codexbridge.companions</string>
<key>CFBundleName</key><string>CodexBridge Companions</string>
<key>CFBundleDisplayName</key><string>CodexBridge Companions</string>
<key>CFBundleExecutable</key><string>Companions</string>
<key>CFBundlePackageType</key><string>APPL</string>
<key>CFBundleShortVersionString</key><string>0.2.0</string>
<key>CFBundleVersion</key><string>2</string>
<key>LSUIElement</key><true/>
<key>LSMinimumSystemVersion</key><string>13.0</string>
<key>NSMicrophoneUsageDescription</key><string>Диктовка включается кнопкой микрофона и завершается через 60 секунд. Отдельная настройка «Реагировать на музыку» включает локальный анализ ритма до её выключения. Аудио не сохраняется.</string>
<key>NSSpeechRecognitionUsageDescription</key><string>macOS преобразует диктовку в текст для OpenCode и распознаёт ваши голосовые команды. Запрос модели отправляется только по команде «Отправить».</string>
</dict></plist>
`);
const result = spawnSync("swiftc", ["-O", "-swift-version", "5", "-module-cache-path", `${root}.local/swift-cache`,
  "-target", `${process.arch === "arm64" ? "arm64" : "x86_64"}-apple-macosx13.0`,
  "-framework", "AppKit", "-framework", "AVFoundation", "-framework", "Speech", "-framework", "SoundAnalysis",
  ...["CharacterView.swift", "SpriteTransition.swift", "IdleMotion.swift", "TeamMotion.swift", "CharacterMotion.swift", "LayeredMotion.swift", "LayeredRig.swift", "WorkMotion.swift", "PoseAnimation.swift", "CharacterBadgeView.swift", "CaptionState.swift", "SpriteCache.swift", "SpriteDepth.swift", "SpeechBubbleView.swift", "DraftMenu.swift", "WindowState.swift", "ScaleControl.swift", "NativeAudioEngine.swift", "NativeAudioStream.swift", "NativeSpeech.swift", "NativeSpeechStatus.swift", "NativeSpeechCommands.swift", "NativeWindow.swift", "VoiceCommands.swift", "MicrophoneTap.swift", "NativeDictation.swift", "MusicRhythm.swift", "MusicMotion.swift", "MusicAnalysis.swift", "MusicCapture.swift", "MusicControl.swift", "MusicIntegration.swift", "main.swift"].map(name => `${native}/${name}`),
  "-o", `${bundle}/Contents/MacOS/Companions`], { cwd: root, stdio: "inherit" });
if (result.status !== 0) process.exit(result.status ?? 1);
const signed = spawnSync("codesign", ["--force", "--sign", "-", "--identifier", "dev.codexbridge.companions", bundle], { cwd: root, stdio: "inherit" });
if (signed.status !== 0) process.exit(signed.status ?? 1);
// Preserve the old executable path for existing locally generated profiles.
rmSync(`${native}/Companions`, { force: true });
symlinkSync("CodexBridge Companions.app/Contents/MacOS/Companions", `${native}/Companions`);
